#!/usr/bin/env node
// The wire schema is authoritative; core ships a mechanically generated copy.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const source = new URL('../schemas/lunum-sem.schema.json', import.meta.url);
const target = new URL('../packages/core/src/semantic-transport-schema.ts', import.meta.url);
const bytes = fs.readFileSync(source);
const hash = createHash('sha256').update(bytes).digest('hex');
const output = '// Generated by scripts/generate-sem-transport.mjs. Do not edit.\n'
  + `export const SEMANTIC_TRANSPORT_SCHEMA_SHA256 = '${hash}' as const;\n`
  + `export const SEMANTIC_TRANSPORT_SCHEMA = ${JSON.stringify(JSON.parse(bytes), null, 2)};\n`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    throw new Error('semantic transport schema drift: run node scripts/generate-sem-transport.mjs');
  }
} else {
  fs.writeFileSync(target, output);
  console.log(`Generated ${fileURLToPath(target)}`);
}
