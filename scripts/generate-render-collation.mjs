#!/usr/bin/env node
// Exports the ICU root collation order that `String.prototype.localeCompare` uses (the renderer's role tie-break)
// from this Node's ICU as per-code-point weights over NFD-stable code points:  crates/lunum-render/data/collation.txt
//   line: <first-cp-hex>[-<last-cp-hex>] <primary0> <secondary> <tertiary>   (primary increments by 1 along a range)
// Primary 0 = completely ignorable (s=t=0) or a combining mark (s>=0x100). Strings are compared on NFD, level by level.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url).pathname;
const variant = new Intl.Collator();                       // what localeCompare uses
const base = new Intl.Collator(undefined, { sensitivity: 'base' });
const accent = new Intl.Collator(undefined, { sensitivity: 'accent' });
const cps = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const s = String.fromCodePoint(cp); // lone surrogates included: ICU gives them implicit weights by code point
  if (s.normalize('NFD') === s) cps.push(cp);
}
const ch = (cp) => String.fromCodePoint(cp);
const ignorable = [], marks = [], letters = [];
for (const cp of cps) {
  if (variant.compare(ch(cp), '') === 0) ignorable.push(cp);
  else if (base.compare(ch(cp), '') === 0) marks.push(cp);
  else letters.push(cp);
}
const rows = new Map(); // cp -> [p,s,t]
for (const cp of ignorable) rows.set(cp, [0, 0, 0]);
marks.sort((a, b) => variant.compare(ch(a), ch(b)) || a - b);
{ let s = 0x100; for (let i = 0; i < marks.length; i++) { if (i > 0 && accent.compare(ch(marks[i - 1]), ch(marks[i])) !== 0) s++; rows.set(marks[i], [0, s, 1]); } }
letters.sort((a, b) => variant.compare(ch(a), ch(b)) || a - b);
{
  let p = 0, sIdx = 0, tIdx = 0;
  for (let i = 0; i < letters.length; i++) {
    const cur = ch(letters[i]);
    if (i === 0) p = 1;
    else {
      const prev = ch(letters[i - 1]);
      if (base.compare(prev, cur) !== 0) { p++; sIdx = 0; tIdx = 0; }
      else if (accent.compare(prev, cur) !== 0) { sIdx++; tIdx = 0; }
      else if (variant.compare(prev, cur) !== 0) tIdx++;
    }
    rows.set(letters[i], [p, 0x20 + sIdx, 1 + tIdx]);
  }
}
const out = [];
let run = null;
const flush = () => { if (run) out.push(`${run.a.toString(16)}${run.b > run.a ? '-' + run.b.toString(16) : ''} ${run.p} ${run.s} ${run.t}`); };
for (const cp of [...rows.keys()].sort((a, b) => a - b)) {
  const [p, s, t] = rows.get(cp);
  if (run && cp === run.b + 1 && s === run.s && t === run.t && p !== 0 && p === run.p + (cp - run.a)) run.b = cp;
  else { flush(); run = { a: cp, b: cp, p, s, t }; }
}
flush();
const lone = 'weighted-by-code-point';
const text = `# GENERATED by scripts/generate-render-collation.mjs from Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}, locale ${variant.resolvedOptions().locale}). Do not edit.\n# lone-surrogates ${lone}\n${out.join('\n')}\n`;
fs.writeFileSync(`${root}crates/lunum-render/data/collation.txt`, text);
fs.writeFileSync(`${root}crates/lunum-render/data/collation.sha256`, createHash('sha256').update(text).digest('hex') + '\n');
console.log(out.length, 'rows', lone, text.length, 'bytes');
