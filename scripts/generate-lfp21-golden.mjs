const LENGTHS = [5, 16, 24.9, 64, 100];
function reasonOf(e) { return e instanceof Error ? e.message.slice(0, 200) : String(e); }
function project(sem) {
  const structural = validateSem(sem);
  if (!structural.ok) throw new TypeError(`structural: ${structural.errors.join('; ')}`);
  const normalization = normalizeSemanticCandidate(sem, { strict: true });
  if (!normalization.sem || !normalization.canonical) throw new TypeError(`non-canonical: ${normalization.issues.map((i) => i.message).join('; ')}`);
  const canonical = canonicalizeSem(normalization.sem);
  const frames = validateSemFrames(canonical);
  if (!frames.valid) throw new TypeError(`frame-invalid: ${frames.issues.map((i) => i.message).join('; ')}`);
  return stableStringify(semanticIdentityProjection(canonical));
}
const entries = [];
function emit(category, source, input, raw) {
  let value = raw !== undefined ? JSON.parse(raw) : input;
  const entry = { category, source };
  if (raw !== undefined) entry.inputRaw = raw;
  else {
    const text = JSON.stringify(input);
    if (text === undefined) { entry.inputRaw = 'null'; value = null; }
    else {
      entry.input = input;
      if (JSON.stringify(JSON.parse(text)) !== text) { entry.inputRaw = text; delete entry.input; }
    }
  }
  try {
    const proj = project(value);
    const lfp = semanticFingerprint(value);
    const digest = createHash('sha256').update(proj).digest('hex');
    if (lfp !== `lfp:2.1:sha256:${digest.slice(0, 32)}`) throw new Error('internal: lfp does not match projection bytes');
    entry.projectionBytes = proj;
    entry.lfp = lfp;
    entry.variants = Object.fromEntries(LENGTHS.map((n) => [String(n), semanticFingerprint(value, { length: n })]));
  } catch (e) {
    entry.rejected = true;
    entry.reason = reasonOf(e);
    let threw = false; try { semanticFingerprint(value); } catch { threw = true; }
    if (!threw) throw new Error('internal: pipeline rejected but semanticFingerprint accepted');
  }
  entries.push(entry);
}
